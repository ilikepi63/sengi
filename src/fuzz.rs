//! Step 5a: generate leaf values directly from a [`Shape`].
//!
//! Values are biased towards variety rather than drawn uniformly, because a
//! uniform `u64` is almost always a huge number and a uniform string is
//! almost always non-ASCII noise:
//!
//! - **integers**: 25% are edge cases (0, 1, −1, MIN, MAX, MAX−1); the rest
//!   pick a random bit width first, so small and huge numbers are equally
//!   likely.
//! - **floats**: 20% are special values (±0, ±∞, NaN, smallest normal and
//!   subnormal, MAX); the rest have a random exponent.
//! - **strings**: a random length bucket (empty, 1–4, 5–16, 17–64) and a
//!   random mix of character classes per string, so strings differ in what
//!   *kind* of characters they hold, not only in length.
//! - **collections**: a random length bucket (empty, 1–3, 4–8, 9–16).
//! - **enums and `Option`**: a uniformly random variant / `Some` or `None`.
//!
//! - **overrides**: a [`Shape::Custom`] part is generated by its override,
//!   as one whole value.
//!
//! Every value is generated directly, so all values are of the right type;
//! domain rules (e.g. "only A, C, G, T") are not known here yet.

use crate::Primitive;
use crate::char_class::{CharClass, classify};
use crate::overrides::Overrides;
use crate::rng::Rng;
use crate::shape::Shape;
use crate::value::{Input, InputLeaf, Kind, LeafValue};

/// Generate one random input with the given shape.
///
/// Every simple value becomes a leaf; enum variants and `Some`/`None` become
/// choice leaves and collection lengths become length leaves (see
/// [`crate::value`]). Ignored and unsupported parts of the shape produce no
/// leaves.
pub fn generate(shape: &Shape, overrides: &Overrides, rng: &mut Rng) -> Input {
    let mut input = Input::new();
    generate_into(shape, "", overrides, rng, &mut input);
    input
}

fn generate_into(
    shape: &Shape,
    path: &str,
    overrides: &Overrides,
    rng: &mut Rng,
    input: &mut Input,
) {
    match shape {
        Shape::Simple(primitive) => {
            let leaf = InputLeaf {
                kind: Kind::Primitive(*primitive),
                value: random_primitive(*primitive, rng),
            };
            input.insert(path.to_string(), leaf);
        }
        Shape::Fields(fields) => {
            for (name, field) in fields {
                generate_into(field, &child(path, name), overrides, rng, input);
            }
        }
        Shape::Enum(variants) => {
            if variants.is_empty() {
                return;
            }
            let (variant, fields) = rng.pick(variants);
            input.insert(path.to_string(), choice(variant));
            for (name, field) in fields {
                let field_path = child(&child(path, variant), name);
                generate_into(field, &field_path, overrides, rng, input);
            }
        }
        Shape::Option(inner) => {
            if rng.chance(0.5) {
                input.insert(path.to_string(), choice("Some"));
                generate_into(inner, &child(path, "Some"), overrides, rng, input);
            } else {
                input.insert(path.to_string(), choice("None"));
            }
        }
        Shape::List(element) => {
            let len = random_length(rng);
            input.insert(child(path, "len"), length(len));
            for i in 0..len {
                generate_into(element, &format!("{path}[{i}]"), overrides, rng, input);
            }
        }
        Shape::Array(element, len) => {
            for i in 0..*len {
                generate_into(element, &format!("{path}[{i}]"), overrides, rng, input);
            }
        }
        Shape::Map(key, value) => {
            let len = random_length(rng);
            input.insert(child(path, "len"), length(len));
            for i in 0..len {
                generate_into(key, &format!("{path}[{i}].key"), overrides, rng, input);
                generate_into(value, &format!("{path}[{i}].value"), overrides, rng, input);
            }
        }
        Shape::Custom(name) => {
            let the_override = overrides
                .get(name)
                .unwrap_or_else(|| panic!("no override registered as `{name}`"));
            let leaf = InputLeaf {
                kind: Kind::Custom(name.clone()),
                value: LeafValue::Custom((the_override.generate)(rng)),
            };
            input.insert(path.to_string(), leaf);
        }
        Shape::Ignored | Shape::Unsupported(_) => {}
    }
}

fn child(path: &str, name: &str) -> String {
    if path.is_empty() {
        name.to_string()
    } else {
        format!("{path}.{name}")
    }
}

fn choice(name: &str) -> InputLeaf {
    InputLeaf {
        kind: Kind::Choice,
        value: LeafValue::Choice(name.to_string()),
    }
}

fn length(len: usize) -> InputLeaf {
    InputLeaf {
        kind: Kind::Length,
        value: LeafValue::Length(len),
    }
}

fn random_length(rng: &mut Rng) -> usize {
    match rng.below(4) {
        0 => 0,
        1 => rng.range(1, 3) as usize,
        2 => rng.range(4, 8) as usize,
        _ => rng.range(9, 16) as usize,
    }
}

fn random_primitive(primitive: Primitive, rng: &mut Rng) -> LeafValue {
    match primitive {
        Primitive::Bool => LeafValue::Bool(rng.chance(0.5)),
        Primitive::U8 => LeafValue::UInt(random_unsigned(8, rng)),
        Primitive::U16 => LeafValue::UInt(random_unsigned(16, rng)),
        Primitive::U32 => LeafValue::UInt(random_unsigned(32, rng)),
        Primitive::U64 => LeafValue::UInt(random_unsigned(64, rng)),
        Primitive::U128 => LeafValue::UInt(random_unsigned(128, rng)),
        Primitive::Usize => LeafValue::UInt(random_unsigned(64, rng)),
        Primitive::I8 => LeafValue::Int(random_signed(8, rng)),
        Primitive::I16 => LeafValue::Int(random_signed(16, rng)),
        Primitive::I32 => LeafValue::Int(random_signed(32, rng)),
        Primitive::I64 => LeafValue::Int(random_signed(64, rng)),
        Primitive::I128 => LeafValue::Int(random_signed(128, rng)),
        Primitive::Isize => LeafValue::Int(random_signed(64, rng)),
        Primitive::F32 => LeafValue::Float(random_f32(rng) as f64),
        Primitive::F64 => LeafValue::Float(random_f64(rng)),
        Primitive::Char => LeafValue::Char(random_char(rng)),
        Primitive::Str | Primitive::String => LeafValue::Text(random_string(rng)),
    }
}

// ---------------------------------------------------------------- integers

fn random_unsigned(bits: u32, rng: &mut Rng) -> u128 {
    let max = unsigned_max(bits);
    if rng.chance(0.25) {
        return *rng.pick(&[0, 1, max - 1, max]);
    }
    let width = rng.range(1, bits as i64) as u32;
    rng.next_u128() & unsigned_max(width)
}

fn random_signed(bits: u32, rng: &mut Rng) -> i128 {
    let (min, max) = if bits == 128 {
        (i128::MIN, i128::MAX)
    } else {
        (-(1 << (bits - 1)), (1 << (bits - 1)) - 1)
    };
    if rng.chance(0.25) {
        return *rng.pick(&[0, 1, -1, min, max]);
    }
    // One bit is the sign, so the magnitude has at most `bits - 1` bits.
    let width = rng.range(1, bits as i64 - 1) as u32;
    let magnitude = (rng.next_u128() & unsigned_max(width)) as i128;
    if rng.chance(0.5) {
        -magnitude
    } else {
        magnitude
    }
}

fn unsigned_max(bits: u32) -> u128 {
    if bits == 128 {
        u128::MAX
    } else {
        (1 << bits) - 1
    }
}

// ---------------------------------------------------------------- floats

fn random_f64(rng: &mut Rng) -> f64 {
    if rng.chance(0.2) {
        let specials = [
            0.0,
            -0.0,
            f64::INFINITY,
            f64::NEG_INFINITY,
            f64::NAN,
            f64::MIN_POSITIVE,
            f64::MAX,
            f64::from_bits(1), // smallest subnormal
        ];
        return *rng.pick(&specials);
    }
    let exponent = rng.range(-1022, 1023) as i32;
    let mantissa = 1.0 + rng.below(1 << 52) as f64 / (1u64 << 52) as f64;
    let sign = if rng.chance(0.5) { -1.0 } else { 1.0 };
    sign * mantissa * 2f64.powi(exponent)
}

fn random_f32(rng: &mut Rng) -> f32 {
    if rng.chance(0.2) {
        let specials = [
            0.0,
            -0.0,
            f32::INFINITY,
            f32::NEG_INFINITY,
            f32::NAN,
            f32::MIN_POSITIVE,
            f32::MAX,
            f32::from_bits(1), // smallest subnormal
        ];
        return *rng.pick(&specials);
    }
    let exponent = rng.range(-126, 127) as i32;
    let mantissa = 1.0 + rng.below(1 << 23) as f32 / (1u32 << 23) as f32;
    let sign = if rng.chance(0.5) { -1.0 } else { 1.0 };
    sign * mantissa * 2f32.powi(exponent)
}

// ---------------------------------------------------------------- chars and strings

const PUNCTUATION: &[u8] = b"!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~";
const WHITESPACE: [char; 5] = [' ', '\t', '\n', '\r', '\x0C'];

fn random_char(rng: &mut Rng) -> char {
    let class = *rng.pick(&CharClass::ALL);
    random_char_of(class, rng)
}

fn random_char_of(class: CharClass, rng: &mut Rng) -> char {
    match class {
        CharClass::Lowercase => (b'a' + rng.below(26) as u8) as char,
        CharClass::Uppercase => (b'A' + rng.below(26) as u8) as char,
        CharClass::Digit => (b'0' + rng.below(10) as u8) as char,
        CharClass::Punctuation => *rng.pick(PUNCTUATION) as char,
        CharClass::Whitespace => *rng.pick(&WHITESPACE),
        CharClass::Control => loop {
            // 0..=31 plus DEL (127), skipping the ones that are whitespace.
            let byte = rng.below(33) as u8;
            let c = if byte == 32 {
                127 as char
            } else {
                byte as char
            };
            if classify(c) == CharClass::Control {
                break c;
            }
        },
        CharClass::NonAscii => loop {
            // Retry on the surrogate range, which isn't a valid char.
            let code = rng.range(0x80, char::MAX as i64) as u32;
            if let Some(c) = char::from_u32(code) {
                break c;
            }
        },
    }
}

fn random_string(rng: &mut Rng) -> String {
    let len = match rng.below(4) {
        0 => 0,
        1 => rng.range(1, 4),
        2 => rng.range(5, 16),
        _ => rng.range(17, 64),
    };

    // Each string uses its own random mix of character classes, so strings
    // differ in *what kind* of characters they contain, not only in length.
    let mut classes = Vec::new();
    for class in CharClass::ALL {
        if rng.chance(0.3) {
            classes.push(class);
        }
    }
    if classes.is_empty() {
        classes.push(*rng.pick(&CharClass::ALL));
    }

    let mut text = String::new();
    for _ in 0..len {
        let class = *rng.pick(&classes);
        text.push(random_char_of(class, rng));
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::function_inputs;
    use crate::shape::function_shape;

    const FIXTURE: &str = include_str!("../tests/fixtures/complex.rs");

    fn configure_shape() -> Shape {
        let functions = function_inputs(FIXTURE).unwrap();
        function_shape(
            functions.iter().find(|f| f.name == "configure").unwrap(),
            &Overrides::new(),
        )
    }

    #[test]
    fn same_seed_same_input() {
        let shape = configure_shape();
        let a = generate(&shape, &Overrides::new(), &mut Rng::new(7));
        let b = generate(&shape, &Overrides::new(), &mut Rng::new(7));
        assert_eq!(a, b);
    }

    #[test]
    fn generates_every_always_present_leaf() {
        let shape = configure_shape();
        let mut rng = Rng::new(1);
        for _ in 0..100 {
            let input = generate(&shape, &Overrides::new(), &mut rng);
            for path in [
                "cfg.name",
                "cfg.retries",
                "cfg.mode",
                "cfg.limits",
                "overrides.inner",
                "overrides.count",
            ] {
                assert!(input.contains_key(path), "missing {path} in {input:?}");
            }
            // The chosen variant's fields are generated, and only those.
            let LeafValue::Choice(mode) = &input["cfg.mode"].value else {
                panic!()
            };
            match mode.as_str() {
                "Fast" => assert!(input.contains_key("cfg.mode.Fast.0")),
                "Custom" => assert!(input.contains_key("cfg.mode.Custom.level")),
                _ => assert!(!input.keys().any(|k| k.starts_with("cfg.mode."))),
            }
        }
    }

    #[test]
    fn integers_stay_in_range_of_their_type() {
        let mut rng = Rng::new(3);
        for _ in 0..10_000 {
            assert!(random_unsigned(8, &mut rng) <= u8::MAX as u128);
            let signed = random_signed(8, &mut rng);
            assert!((i8::MIN as i128..=i8::MAX as i128).contains(&signed));
        }
    }

    #[test]
    fn list_length_matches_generated_elements() {
        let shape = Shape::List(Box::new(Shape::Simple(Primitive::Bool)));
        let mut rng = Rng::new(5);
        for _ in 0..100 {
            let input = generate(&shape, &Overrides::new(), &mut rng);
            let LeafValue::Length(len) = input["len"].value else {
                panic!()
            };
            assert_eq!(input.len(), len + 1); // the elements plus `len`
        }
    }
}
