//! Step 5a: generate leaf values directly from a [`Shape`].
//!
//! Values are biased towards variety rather than drawn uniformly, because a
//! uniform `u64` is almost always a huge number and a uniform string is
//! almost always non-ASCII noise. Every value stays inside its range (see
//! [`Simple`]):
//!
//! - **integers**: 25% are edge cases (0, 1, −1 and both ends of the range,
//!   plus one step in from each end); the rest pick a random bit width first,
//!   so small and huge numbers are equally likely.
//! - **floats**: 20% are edge cases (Rust floats: ±0, ±∞, NaN, smallest
//!   normal and subnormal, MAX; limited ranges: both ends and 0); the rest
//!   are half spread evenly over the range and half spread over exponents.
//! - **strings and collections**: a random length on a log scale (0, 1,
//!   2–3, 4–7, ...) within the allowed lengths; strings have no limit by
//!   default but stop at 64, collections at 16. Each string gets a random mix
//!   of character classes, so strings differ in what *kind* of characters
//!   they hold, not only in length.
//! - **enums, unions, literals and `Option`**: a uniformly random choice.
//! - **overrides**: a [`Shape::Custom`] part is generated by its override,
//!   as one whole value.
//!
//! Every value is generated directly, so all values are of the right type;
//! domain rules (e.g. "only A, C, G, T") need an override.

use crate::char_class::{CharClass, classify};
use crate::overrides::Overrides;
use crate::params::{bit_length, unsigned_max};
use crate::rng::Rng;
use crate::shape::{Len, Shape, Simple, literal_label};
use crate::value::{Input, InputLeaf, Kind, LeafValue};

/// Longest generated string when the shape sets no limit.
const DEFAULT_TEXT_SPAN: usize = 64;
/// Longest generated collection when the shape sets no limit.
const DEFAULT_LIST_SPAN: usize = 16;

/// Generate one random input with the given shape.
///
/// Every simple value becomes a leaf; enum variants, union members, literals
/// and `Some`/`None` become choice leaves and collection lengths become
/// length leaves (see [`crate::value`]). Ignored and unsupported parts of the
/// shape produce no leaves.
pub fn generate(shape: &Shape, overrides: &Overrides, rng: &mut Rng) -> Input {
    let mut input = Input::new();
    generate_into(shape, "", overrides, rng, &mut input);
    input
}

fn generate_into(
    shape: &Shape,
    path: &str,
    overrides: &Overrides,
    rng: &mut Rng,
    input: &mut Input,
) {
    match shape {
        Shape::Simple(simple) => {
            let leaf = InputLeaf {
                kind: Kind::Simple(*simple),
                value: random_simple(simple, rng),
            };
            input.insert(path.to_string(), leaf);
        }
        Shape::Fields(fields) => {
            for (name, field) in fields {
                generate_into(field, &child(path, name), overrides, rng, input);
            }
        }
        Shape::Enum(variants) => {
            if variants.is_empty() {
                return;
            }
            let (variant, fields) = rng.pick(variants);
            input.insert(path.to_string(), choice(variant));
            for (name, field) in fields {
                let field_path = child(&child(path, variant), name);
                generate_into(field, &field_path, overrides, rng, input);
            }
        }
        Shape::Union(members) => {
            if members.is_empty() {
                return;
            }
            let (label, member) = rng.pick(members);
            input.insert(path.to_string(), choice(label));
            generate_into(member, &child(path, label), overrides, rng, input);
        }
        Shape::Literal(values) => {
            // A constant has nothing to choose, so it needs no leaf.
            if values.len() < 2 {
                return;
            }
            let value = rng.pick(values);
            input.insert(path.to_string(), choice(&literal_label(value)));
        }
        Shape::Option(inner) | Shape::Optional(inner) => {
            // An optional property that can't be generated is left out,
            // rather than written as an invalid value.
            let can_generate = !matches!(**inner, Shape::Unsupported(_) | Shape::Ignored);
            let leave_out = matches!(shape, Shape::Optional(_)) && !can_generate;
            if !leave_out && rng.chance(0.5) {
                input.insert(path.to_string(), choice("Some"));
                generate_into(inner, &child(path, "Some"), overrides, rng, input);
            } else {
                input.insert(path.to_string(), choice("None"));
            }
        }
        Shape::List(element, len) => {
            let len = random_length(len, DEFAULT_LIST_SPAN, rng);
            input.insert(child(path, "len"), length(len));
            for i in 0..len {
                generate_into(element, &format!("{path}[{i}]"), overrides, rng, input);
            }
        }
        Shape::Array(element, len) => {
            for i in 0..*len {
                generate_into(element, &format!("{path}[{i}]"), overrides, rng, input);
            }
        }
        Shape::Map(key, value, len) => {
            let len = random_length(len, DEFAULT_LIST_SPAN, rng);
            input.insert(child(path, "len"), length(len));
            for i in 0..len {
                generate_into(key, &format!("{path}[{i}].key"), overrides, rng, input);
                generate_into(value, &format!("{path}[{i}].value"), overrides, rng, input);
            }
        }
        Shape::Custom(name) => {
            let the_override = overrides
                .get(name)
                .unwrap_or_else(|| panic!("no override registered as `{name}`"));
            let leaf = InputLeaf {
                kind: Kind::Custom(name.clone()),
                value: LeafValue::Custom((the_override.generate)(rng)),
            };
            input.insert(path.to_string(), leaf);
        }
        Shape::Ignored | Shape::Unsupported(_) => {}
    }
}

fn child(path: &str, name: &str) -> String {
    if path.is_empty() {
        name.to_string()
    } else {
        format!("{path}.{name}")
    }
}

fn choice(name: &str) -> InputLeaf {
    InputLeaf {
        kind: Kind::Choice,
        value: LeafValue::Choice(name.to_string()),
    }
}

fn length(len: usize) -> InputLeaf {
    InputLeaf {
        kind: Kind::Length,
        value: LeafValue::Length(len),
    }
}

/// A length within `len`; without an upper limit, at most `default_span`
/// above the minimum.
fn random_length(len: &Len, default_span: usize, rng: &mut Rng) -> usize {
    let max = len.max.unwrap_or(len.min + default_span).max(len.min);
    len.min + random_up_to(max - len.min, rng)
}

/// A number in `0..=span` on a log scale: 0, 1, 2–3, 4–7, ... are equally
/// likely, so short and long are both common.
fn random_up_to(span: usize, rng: &mut Rng) -> usize {
    if span == 0 {
        return 0;
    }
    let width = rng.range(0, bit_length(span as u128) as i64) as u32;
    if width == 0 {
        return 0;
    }
    let low = 1usize << (width - 1);
    let high = (unsigned_max(width) as usize).min(span);
    rng.range(low as i64, high as i64) as usize
}

fn random_simple(simple: &Simple, rng: &mut Rng) -> LeafValue {
    match *simple {
        Simple::Bool => LeafValue::Bool(rng.chance(0.5)),
        Simple::UInt { min, max } => LeafValue::UInt(random_unsigned(min, max, rng)),
        Simple::Int { min, max } => LeafValue::Int(random_signed(min, max, rng)),
        Simple::Float {
            min,
            max,
            single,
            specials,
        } => LeafValue::Float(random_float(min, max, single, specials, rng)),
        Simple::Char => LeafValue::Char(random_char(rng)),
        Simple::Text { min_len, max_len } => {
            let len = Len {
                min: min_len,
                max: max_len,
            };
            LeafValue::Text(random_string(
                random_length(&len, DEFAULT_TEXT_SPAN, rng),
                rng,
            ))
        }
    }
}

// ---------------------------------------------------------------- integers

fn random_unsigned(min: u128, max: u128, rng: &mut Rng) -> u128 {
    if rng.chance(0.25) {
        let candidates = [
            Some(0),
            Some(1),
            Some(min),
            min.checked_add(1),
            max.checked_sub(1),
            Some(max),
        ];
        return *rng.pick(&edges(candidates, |v| (min..=max).contains(v)));
    }
    let span = max - min;
    let width = rng.range(1, bit_length(span).max(1) as i64) as u32;
    let mut offset = rng.next_u128() & unsigned_max(width);
    if offset > span {
        // Only possible in the widest bucket; `span < u128::MAX` here.
        offset %= span + 1;
    }
    min + offset
}

fn random_signed(min: i128, max: i128, rng: &mut Rng) -> i128 {
    if rng.chance(0.25) {
        let candidates = [
            Some(0),
            Some(1),
            Some(-1),
            Some(min),
            min.checked_add(1),
            max.checked_sub(1),
            Some(max),
        ];
        return *rng.pick(&edges(candidates, |v| (min..=max).contains(v)));
    }
    // Start from zero (or the end of the range nearest it), pick a side with
    // room on it, then a distance with a random bit width.
    let origin = 0.clamp(min, max);
    let up = max.abs_diff(origin);
    let down = min.abs_diff(origin);
    let go_up = match (up, down) {
        (0, 0) => return origin,
        (0, _) => false,
        (_, 0) => true,
        _ => rng.chance(0.5),
    };
    let room = if go_up { up } else { down };
    let width = rng.range(1, bit_length(room) as i64) as u32;
    let mut offset = rng.next_u128() & unsigned_max(width);
    if offset > room {
        // `room` is at most 2^127, so `room + 1` can't overflow.
        offset %= room + 1;
    }
    if go_up {
        origin.saturating_add_unsigned(offset)
    } else {
        origin.saturating_sub_unsigned(offset)
    }
}

/// The candidates that exist and pass `keep`, without duplicates.
fn edges<T: Copy + Ord>(
    candidates: impl IntoIterator<Item = Option<T>>,
    keep: impl Fn(&T) -> bool,
) -> Vec<T> {
    let mut found: Vec<T> = candidates
        .into_iter()
        .flatten()
        .filter(|v| keep(v))
        .collect();
    found.sort();
    found.dedup();
    found
}

// ---------------------------------------------------------------- floats

fn random_float(min: f64, max: f64, single: bool, specials: bool, rng: &mut Rng) -> f64 {
    if specials {
        // A whole Rust float type: its own specials and exponents.
        return if single {
            random_f32(rng) as f64
        } else {
            random_f64(rng)
        };
    }

    if rng.chance(0.2) {
        let mut candidates = vec![min, max];
        if min <= 0.0 && 0.0 <= max {
            candidates.push(0.0);
        }
        return *rng.pick(&candidates);
    }

    let unit = |rng: &mut Rng| (rng.next_u64() >> 11) as f64 / (1u64 << 53) as f64;
    let value = if rng.chance(0.5) {
        // Evenly over the range; written so `max - min` can't overflow.
        let u = unit(rng);
        min * (1.0 - u) + max * u
    } else {
        // Over the exponents below the range's largest magnitude, retried
        // until the value lands in the range.
        let largest = min.abs().max(max.abs()).max(f64::MIN_POSITIVE);
        let top = largest.log2().ceil() as i32;
        let bottom = (top - 64).max(-1022);
        let mut found = None;
        for _ in 0..32 {
            let exponent = rng.range(bottom as i64, top as i64) as i32;
            let magnitude = (1.0 + unit(rng)) * 2f64.powi(exponent - 1);
            let candidate = if rng.chance(0.5) {
                -magnitude
            } else {
                magnitude
            };
            if (min..=max).contains(&candidate) {
                found = Some(candidate);
                break;
            }
        }
        found.unwrap_or_else(|| {
            let u = unit(rng);
            min * (1.0 - u) + max * u
        })
    };

    if single {
        // Rounding to f32 can step just outside the range.
        (value as f32 as f64).clamp(min, max)
    } else {
        value
    }
}

fn random_f64(rng: &mut Rng) -> f64 {
    if rng.chance(0.2) {
        let specials = [
            0.0,
            -0.0,
            f64::INFINITY,
            f64::NEG_INFINITY,
            f64::NAN,
            f64::MIN_POSITIVE,
            f64::MAX,
            f64::from_bits(1), // smallest subnormal
        ];
        return *rng.pick(&specials);
    }
    let exponent = rng.range(-1022, 1023) as i32;
    let mantissa = 1.0 + rng.below(1 << 52) as f64 / (1u64 << 52) as f64;
    let sign = if rng.chance(0.5) { -1.0 } else { 1.0 };
    sign * mantissa * 2f64.powi(exponent)
}

fn random_f32(rng: &mut Rng) -> f32 {
    if rng.chance(0.2) {
        let specials = [
            0.0,
            -0.0,
            f32::INFINITY,
            f32::NEG_INFINITY,
            f32::NAN,
            f32::MIN_POSITIVE,
            f32::MAX,
            f32::from_bits(1), // smallest subnormal
        ];
        return *rng.pick(&specials);
    }
    let exponent = rng.range(-126, 127) as i32;
    let mantissa = 1.0 + rng.below(1 << 23) as f32 / (1u32 << 23) as f32;
    let sign = if rng.chance(0.5) { -1.0 } else { 1.0 };
    sign * mantissa * 2f32.powi(exponent)
}

// ---------------------------------------------------------------- chars and strings

const PUNCTUATION: &[u8] = b"!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~";
const WHITESPACE: [char; 5] = [' ', '\t', '\n', '\r', '\x0C'];

fn random_char(rng: &mut Rng) -> char {
    let class = *rng.pick(&CharClass::ALL);
    random_char_of(class, rng)
}

fn random_char_of(class: CharClass, rng: &mut Rng) -> char {
    match class {
        CharClass::Lowercase => (b'a' + rng.below(26) as u8) as char,
        CharClass::Uppercase => (b'A' + rng.below(26) as u8) as char,
        CharClass::Digit => (b'0' + rng.below(10) as u8) as char,
        CharClass::Punctuation => *rng.pick(PUNCTUATION) as char,
        CharClass::Whitespace => *rng.pick(&WHITESPACE),
        CharClass::Control => loop {
            // 0..=31 plus DEL (127), skipping the ones that are whitespace.
            let byte = rng.below(33) as u8;
            let c = if byte == 32 {
                127 as char
            } else {
                byte as char
            };
            if classify(c) == CharClass::Control {
                break c;
            }
        },
        CharClass::NonAscii => loop {
            // Retry on the surrogate range, which isn't a valid char.
            let code = rng.range(0x80, char::MAX as i64) as u32;
            if let Some(c) = char::from_u32(code) {
                break c;
            }
        },
    }
}

/// A string of `len` characters.
fn random_string(len: usize, rng: &mut Rng) -> String {
    // Each string uses its own random mix of character classes, so strings
    // differ in *what kind* of characters they contain, not only in length.
    let mut classes = Vec::new();
    for class in CharClass::ALL {
        if rng.chance(0.3) {
            classes.push(class);
        }
    }
    if classes.is_empty() {
        classes.push(*rng.pick(&CharClass::ALL));
    }

    let mut text = String::new();
    for _ in 0..len {
        let class = *rng.pick(&classes);
        text.push(random_char_of(class, rng));
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::function_inputs;
    use crate::shape::function_shape;

    const FIXTURE: &str = include_str!("../tests/fixtures/complex.rs");

    fn configure_shape() -> Shape {
        let functions = function_inputs(FIXTURE).unwrap();
        function_shape(
            functions.iter().find(|f| f.name == "configure").unwrap(),
            &Overrides::new(),
        )
    }

    #[test]
    fn same_seed_same_input() {
        let shape = configure_shape();
        let a = generate(&shape, &Overrides::new(), &mut Rng::new(7));
        let b = generate(&shape, &Overrides::new(), &mut Rng::new(7));
        assert_eq!(a, b);
    }

    #[test]
    fn generates_every_always_present_leaf() {
        let shape = configure_shape();
        let mut rng = Rng::new(1);
        for _ in 0..100 {
            let input = generate(&shape, &Overrides::new(), &mut rng);
            for path in [
                "cfg.name",
                "cfg.retries",
                "cfg.mode",
                "cfg.limits",
                "overrides.inner",
                "overrides.count",
            ] {
                assert!(input.contains_key(path), "missing {path} in {input:?}");
            }
            // The chosen variant's fields are generated, and only those.
            let LeafValue::Choice(mode) = &input["cfg.mode"].value else {
                panic!()
            };
            match mode.as_str() {
                "Fast" => assert!(input.contains_key("cfg.mode.Fast.0")),
                "Custom" => assert!(input.contains_key("cfg.mode.Custom.level")),
                _ => assert!(!input.keys().any(|k| k.starts_with("cfg.mode."))),
            }
        }
    }

    #[test]
    fn integers_stay_in_range_of_their_type() {
        let mut rng = Rng::new(3);
        for _ in 0..10_000 {
            assert!(random_unsigned(0, u8::MAX as u128, &mut rng) <= u8::MAX as u128);
            let signed = random_signed(i8::MIN as i128, i8::MAX as i128, &mut rng);
            assert!((i8::MIN as i128..=i8::MAX as i128).contains(&signed));
        }
    }

    #[test]
    fn values_stay_inside_narrow_ranges() {
        let mut rng = Rng::new(9);
        for _ in 0..10_000 {
            let u = random_unsigned(5, 10, &mut rng);
            assert!((5..=10).contains(&u), "{u}");
            let i = random_signed(-100, -50, &mut rng);
            assert!((-100..=-50).contains(&i), "{i}");
            let f = random_float(0.5, 2.5, false, false, &mut rng);
            assert!((0.5..=2.5).contains(&f), "{f}");
            let len = random_length(
                &Len {
                    min: 3,
                    max: Some(5),
                },
                16,
                &mut rng,
            );
            assert!((3..=5).contains(&len), "{len}");
        }
        // Both ends of the range come up.
        let values: Vec<u128> = (0..1000)
            .map(|_| random_unsigned(5, 10, &mut rng))
            .collect();
        assert!(values.contains(&5) && values.contains(&10));
    }

    #[test]
    fn list_length_matches_generated_elements() {
        let shape = Shape::List(Box::new(Shape::Simple(Simple::Bool)), Len::default());
        let mut rng = Rng::new(5);
        for _ in 0..100 {
            let input = generate(&shape, &Overrides::new(), &mut rng);
            let LeafValue::Length(len) = input["len"].value else {
                panic!()
            };
            assert_eq!(input.len(), len + 1); // the elements plus `len`
        }
    }
}
